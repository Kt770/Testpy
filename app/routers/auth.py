@router.delete("/users/{user_id}")
async def delete_user(
    user_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(require_admin)
):
    """Delete user (admin only)."""
    user = db.query(User).filter(User.id == user_id).first()
    if not user:
        raise HTTPException(status_code=404, detail="User not found")
    
    # Prevent admin from deleting themselves
    if user.id == current_user.id:
        raise HTTPException(
            status_code=400,
            detail="Cannot delete your own account"
        )
    
    # Check if user has created contracts or proposals
    from app.models.models import Contract, Proposal
    user_contracts = db.query(Contract).filter(Contract.created_by == user_id).count()
    user_proposals = db.query(Proposal).filter(Proposal.reviewed_by == user_id).count()
    
    if user_contracts > 0 or user_proposals > 0:
        # Soft delete by deactivating instead of hard delete
        user.is_active = False
        db.commit()
        return {"message": f"User deactivated (had {user_contracts} contracts and {user_proposals} proposal reviews)"}
    else:
        # Hard delete if no dependencies
        db.delete(user)
        db.commit()
        return {"message": "User deleted successfully"}


